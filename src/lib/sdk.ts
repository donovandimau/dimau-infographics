import { createHash } from 'crypto';
import type { InfographicTemplate } from './types';

const esc = (s: string) => s.replace(/\*\//g, '*\\/').replace(/"/g, '\\"');

/**
 * Build the typed client file sister apps import (src/lib/infographics-fiji.ts in each app).
 * Stamped with a hash of the templates rather than a time, so it only changes when templates change.
 */
export function buildSdk(templates: Pick<InfographicTemplate, 'slug' | 'variables' | 'card_dsl'>[], baseUrl: string): string {
  const sorted = [...templates].sort((a, b) => a.slug.localeCompare(b.slug));
  const stamp = createHash('sha256')
    .update(JSON.stringify(sorted.map((t) => [t.slug, t.variables.map((v) => [v.name, v.default]), !!t.card_dsl])))
    .digest('hex')
    .slice(0, 12);

  const map = sorted
    .map(
      (t) =>
        `  '${t.slug}': {\n` +
        t.variables.map((v) => `    /** Default: "${esc(v.default)}" */\n    ${v.name}?: string | number;`).join('\n') +
        `\n  };`,
    )
    .join('\n');

  return `// AUTO-GENERATED BY INFOGRAPHICS FIJI — DO NOT EDIT. Templates hash: ${stamp}
export type InfographicFormat = 'svg' | 'png';
export type InfographicTheme = 'dark' | 'light';
export type InfographicVariant = 'main' | 'card';

export interface InfographicTemplateMap {
${map}
}

export type TemplateSlug = keyof InfographicTemplateMap;
type Opts = { format?: InfographicFormat; theme?: InfographicTheme; variant?: InfographicVariant };

export const INFOGRAPHICS_BASE_URL = '${baseUrl}';

/** Public embed URL (public templates only). Safe for <img src> and link previews. */
export function getInfographicUrl<T extends TemplateSlug>(slug: T, vars: InfographicTemplateMap[T], o: Opts = {}): string {
  const p = new URLSearchParams();
  for (const [k, v] of Object.entries(vars)) if (v !== undefined && v !== null) p.set(k, String(v));
  for (const [k, v] of Object.entries(o)) if (v) p.set(k, v);
  return \`\${INFOGRAPHICS_BASE_URL}/api/v1/render/\${slug}?\${p}\`;
}

/** Server-side render with an API key (works for private templates). Never call this from browser code. */
export async function renderInfographic<T extends TemplateSlug>(
  slug: T,
  data: InfographicTemplateMap[T],
  apiKey: string,
  o: Opts = {},
): Promise<Response> {
  return fetch(\`\${INFOGRAPHICS_BASE_URL}/api/v1/render/\${slug}\`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-api-key': apiKey },
    body: JSON.stringify({ data, format: o.format ?? 'svg', theme: o.theme ?? 'dark', variant: o.variant ?? 'main' }),
  });
}
`;
}

export const DEFAULT_BASE_URL = process.env.NEXT_PUBLIC_APP_URL ?? 'https://infographics.dimau-fintech.com';
